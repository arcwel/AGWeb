#!/usr/bin/env node
// Builds the third-party license inventory from what actually ships.
//
// Two outputs, one source of truth:
//   THIRD_PARTY_LICENSES.md                          — for someone reading the repo
//   src/renderer/src/generated/third-party-licenses.json — for Settings → About
//
// The list is generated from the app's real dependencies (their own
// package.json license fields), not hand-maintained, so it cannot drift from
// what is installed. The two foundations that are not npm packages — the
// Chromium browser base and the Node runtime the core embeds — are added
// explicitly, and the browser's own components are left to chrome://credits,
// which Chromium already generates for exactly this purpose.
//
// Usage: node scripts/gen-licenses.mjs [--check]
import { existsSync, readFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { NODE_VERSION } from './fetch-node-runtime.mjs'

const appRoot = dirname(dirname(fileURLToPath(import.meta.url)))
const repoRoot = dirname(appRoot)
const checkOnly = process.argv.includes('--check')

const pkg = JSON.parse(readFileSync(join(appRoot, 'package.json'), 'utf8'))

/** Read one installed dependency's license metadata. */
function readDep(name) {
  const manifestPath = join(appRoot, 'node_modules', name, 'package.json')
  if (!existsSync(manifestPath)) return null
  const m = JSON.parse(readFileSync(manifestPath, 'utf8'))
  const license =
    typeof m.license === 'string'
      ? m.license
      : m.license?.type ||
        (Array.isArray(m.licenses) ? m.licenses.map((l) => l.type).join(', ') : '')
  return {
    name,
    version: m.version ?? '',
    license: license || 'see package',
    homepage: m.homepage || m.repository?.url?.replace(/^git\+/, '').replace(/\.git$/, '') || ''
  }
}

// The npm dependencies that ship, deduped and sorted. The @codingame/* set is
// the VS Code service layer — dozens of packages under one project — so it is
// collapsed to a single credit rather than listed twenty times.
const seen = new Set()
const deps = []
for (const name of Object.keys(pkg.dependencies ?? {})) {
  const key = name.startsWith('@codingame/') ? '@codingame/monaco-vscode-api' : name
  if (seen.has(key)) continue
  seen.add(key)
  const entry = readDep(name.startsWith('@codingame/') ? '@codingame/monaco-vscode-api' : name)
  if (entry) deps.push(entry)
}
// ws is used by webdeck-core's transport but is a transitive dep, not a direct one.
if (!seen.has('ws')) {
  const wsEntry = readDep('ws')
  if (wsEntry) deps.push(wsEntry)
}
deps.sort((a, b) => a.name.localeCompare(b.name))

// The two non-npm foundations, credited explicitly.
const foundations = [
  {
    name: 'Chromium',
    version: '153.0.8010.12',
    license: 'BSD-3-Clause',
    homepage: 'https://www.chromium.org/',
    note: 'Arcwel WebDeck is a derivative of Chromium. Chromium and its own third-party components are credited in the app at chrome://credits.'
  },
  {
    name: 'Node.js',
    version: NODE_VERSION,
    license: 'MIT',
    homepage: 'https://nodejs.org/',
    note: 'Embedded in webdeck-core. Includes components under their own licenses (V8, libuv, and others), reproduced with the Node distribution.'
  }
]

const manifest = {
  product: 'Arcwel WebDeck',
  productLicense: 'MIT',
  generated: 'by scripts/gen-licenses.mjs from installed dependencies',
  foundations,
  dependencies: deps
}

// ── outputs ──────────────────────────────────────────────────────────────────
const jsonDir = join(appRoot, 'src', 'renderer', 'src', 'generated')
const jsonPath = join(jsonDir, 'third-party-licenses.json')

const mdLines = [
  '# Third-party licenses',
  '',
  'Arcwel WebDeck is MIT licensed (see [LICENSE](LICENSE)). It bundles the',
  'components below, each under its own license. This file is generated by',
  '`app/scripts/gen-licenses.mjs` from the installed dependencies — do not edit',
  'it by hand.',
  '',
  '## Foundations',
  ''
]
for (const f of foundations) {
  mdLines.push(`### ${f.name} ${f.version} — ${f.license}`, '', f.note, '', `<${f.homepage}>`, '')
}
mdLines.push(
  '## Application dependencies',
  '',
  '| Component | Version | License |',
  '| --- | --- | --- |'
)
for (const d of deps) {
  const nameCell = d.homepage ? `[${d.name}](${d.homepage})` : d.name
  mdLines.push(`| ${nameCell} | ${d.version} | ${d.license} |`)
}
mdLines.push('')
const md = mdLines.join('\n')
const json = JSON.stringify(manifest, null, 2) + '\n'

if (checkOnly) {
  const curMd = existsSync(join(repoRoot, 'THIRD_PARTY_LICENSES.md'))
    ? readFileSync(join(repoRoot, 'THIRD_PARTY_LICENSES.md'), 'utf8')
    : ''
  const curJson = existsSync(jsonPath) ? readFileSync(jsonPath, 'utf8') : ''
  if (curMd !== md || curJson !== json) {
    console.error('third-party license inventory is stale — run: npm run gen:licenses')
    process.exit(1)
  }
  console.log('third-party license inventory is up to date')
  process.exit(0)
}

mkdirSync(jsonDir, { recursive: true })
writeFileSync(jsonPath, json)
writeFileSync(join(repoRoot, 'THIRD_PARTY_LICENSES.md'), md)
console.log(`${deps.length} dependencies + ${foundations.length} foundations`)
console.log(`  -> THIRD_PARTY_LICENSES.md`)
console.log(`  -> ${jsonPath.replace(appRoot + '/', '')}`)
